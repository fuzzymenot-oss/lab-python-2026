def write_files() -> None:
    LAB.mkdir(parents=True, exist_ok=True)
    for path, text in FILES.items():
        path.write_text(text, encoding="utf-8")
        print("записан", path.relative_to(ROOT))


def run_program(filename: str, stdin_text: str) -> str:
    env = os.environ.copy()
    env["PYTHONIOENCODING"] = "utf-8"
    result = subprocess.run(
        [sys.executable, str(LAB / filename)],
        input=stdin_text,
        capture_output=True,
        text=True,
        encoding="utf-8",
        env=env,
        check=False,
    )
    if result.returncode != 0:
        raise RuntimeError(
            f"{filename} завершился с кодом {result.returncode}\n{result.stderr}"
        )
    return result.stdout


def expect_contains(title: str, output: str, fragments: list[str]) -> None:
    missing = [item for item in fragments if item not in output]
    if missing:
        raise AssertionError(
            f"{title}: в выводе нет {missing!r}\n----- вывод -----\n{output}"
        )
    print("  OK ", title)


